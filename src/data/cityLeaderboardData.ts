export const NEARBY_CITIES_LIST = CITIES_LEADERBOARD.filter((c) => c.id !== 'rewa');

export function getRandomNearbyCity(currentCityId: string = 'rewa'): CityLeaderboard {
  const candidates = NEARBY_CITIES_LIST.filter((c) => c.id !== currentCityId);
  const randomIndex = Math.floor(Math.random() * candidates.length);
  return candidates[randomIndex] || NEARBY_CITIES_LIST[0];
}
